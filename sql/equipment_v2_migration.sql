-- ---------- 3. 更新 eq_card：先按最终目标id折叠重复配置行，再换新id/新名/新大类子类，清被动，重写介绍 ----------
-- 说明：v2 每个(前缀,星级段位)仅3个编号位，多个老变体（当初靠拼接uuid保证唯一）必然折叠到同一 new_id；
--       eq_card.id 有唯一索引 uk_eq_card_id，直接 UPDATE 会报 1062 Duplicate entry。
--       故先对同一 final_id 只保留一个代表行（优先保留本就已是该id的行，其次uuid最小），删除其余重复行；
--       只删 eq_card、不动 equip_id_migration，第4步仍会把所有老变体的 eq_characters.id 重挂到唯一保留的 new_id 上。
SET SESSION group_concat_max_len = 1000000;

-- 3.1 每行的最终目标 id：迁移行=new_id，未迁移行=当前 id；need_change=0 表示当前已是目标id（优先当代表）
DROP TABLE IF EXISTS eq_card_final;
CREATE TABLE eq_card_final AS
SELECT ec.uuid,
       COALESCE(m.new_id, ec.id) AS final_id,
       IF(m.old_id IS NULL, 0, 1) AS need_change
FROM eq_card ec
LEFT JOIN equip_id_migration m ON m.old_id = ec.id;

-- 3.2 每个 final_id 选一个代表（仅统计有重复的组）：优先 need_change=0，其次 uuid 最小
DROP TABLE IF EXISTS eq_card_dup;
CREATE TABLE eq_card_dup AS
SELECT final_id,
       SUBSTRING_INDEX(GROUP_CONCAT(uuid ORDER BY need_change ASC, uuid ASC), ',', 1) + 0 AS keep_uuid
FROM eq_card_final
GROUP BY final_id
HAVING COUNT(*) > 1;

-- 3.3 删除同 final_id 的非代表行（折叠重复配置）
DELETE ec
FROM eq_card ec
JOIN eq_card_final f ON f.uuid = ec.uuid
JOIN eq_card_dup  d ON d.final_id = f.final_id
WHERE ec.uuid <> d.keep_uuid;

-- 3.4 现在每个 final_id 只剩一行，安全执行改名+改字段
UPDATE eq_card ec
JOIN equip_id_migration m ON ec.id = m.old_id
SET ec.id            = m.new_id,
    ec.name          = m.new_name,
    ec.eq_type       = m.new_eq_type,
    ec.eq_type2      = m.new_eq_type2,
    ec.introduce     = m.new_introduce,
    ec.passive_introduce_one    = NULL,
    ec.passive_introduce_two    = NULL,
    ec.passive_introduce_three  = NULL;

-- 3.5 清理辅助表
DROP TABLE eq_card_final;
DROP TABLE eq_card_dup;

-- ---------- 4. 更新玩家持有表：仅换 id，lv/exp/max_lv/flyup/xilian/is_suo/stack_count/go_into_num 不动 ----------
UPDATE eq_characters cs
JOIN equip_id_migration m ON cs.id = m.old_id
SET cs.id = m.new_id;

