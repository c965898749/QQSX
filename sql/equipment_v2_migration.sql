-- ---------- 2. 生成 id 映射表（从 eq_card 快照，确定性可复现） ----------
DROP TABLE IF EXISTS equip_id_migration;
CREATE TABLE equip_id_migration (
  old_id VARCHAR(64) NOT NULL PRIMARY KEY,
  new_id VARCHAR(64) NOT NULL,
  new_name VARCHAR(128) NOT NULL,
  new_introduce VARCHAR(255) NULL,
  new_eq_type INT NOT NULL,
  new_eq_type2 INT NOT NULL,
  KEY idx_new_id (new_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

INSERT INTO equip_id_migration (old_id, new_id, new_name, new_introduce, new_eq_type, new_eq_type2)
SELECT
  t.old_id,
  CONCAT(t.new_prefix, LPAD(t.new_num,3,'0'), t.suffix) AS new_id,
  CONCAT(IF(t.attr_part='', '', CONCAT(t.attr_part,'.')), p.equip_name) AS new_name,
  CONCAT(p.equip_name, '，取山川之精、铸百炼之形，', p.type_name, '中暗藏洪荒之力。') AS new_introduce,
  ELT(FIELD(t.new_prefix,'J','G','F','C','T','X','Z','N','P','Y','H','B'),0,0,0,1,1,1,2,2,2,3,3,3) AS new_eq_type,
  FIELD(t.new_prefix,'J','G','F','C','T','X','Z','N','P','Y','H','B') AS new_eq_type2
FROM (
  SELECT
    ec.id AS old_id,
    CASE LEFT(ec.id,1)
      WHEN 'J' THEN 'J' WHEN 'G' THEN 'G' WHEN 'Q' THEN 'F'
      WHEN 'S' THEN 'C' WHEN 'M' THEN 'T' WHEN 'Y' THEN 'X'
      WHEN 'D' THEN 'Z' WHEN 'P' THEN 'P'
      WHEN 'X' THEN IF(CRC32(ec.id) % 2 = 0, 'N', 'P')
      WHEN 'K' THEN ELT(1 + CRC32(ec.id) % 3, 'Y', 'H', 'B')
      WHEN 'F' THEN 'F'          -- 历史孤儿前缀F并入法杖
      ELSE LEFT(ec.id,1) END AS new_prefix,
    CASE ec.star
      WHEN 1.0 THEN 1  WHEN 1.5 THEN 4  WHEN 2.0 THEN 7  WHEN 2.5 THEN 10 WHEN 3.0 THEN 13
      WHEN 3.5 THEN 16 WHEN 4.0 THEN 19 WHEN 4.5 THEN 22 WHEN 5.0 THEN 25 ELSE 1 END
      + CRC32(ec.id) % 3 AS new_num,
    IF(LOCATE('_', ec.id) > 0,
       SUBSTRING(ec.id, LOCATE('_', ec.id)),               -- 保留 _属性后缀（含历史追加的uuid数字）
       CONCAT('_', LPAD(ec.uuid % 900 + 100, 3, '0'))) AS suffix,   -- 无下划线的老id用uuid造后缀，保证新id唯一
    IF(LOCATE('.', ec.name) > 0,
       SUBSTRING_INDEX(ec.name, '.', CHAR_LENGTH(ec.name) - CHAR_LENGTH(REPLACE(ec.name, '.', ''))),
       '') AS attr_part
  FROM eq_card ec
) t
JOIN eq_name_pool p ON p.prefix = t.new_prefix AND p.num = t.new_num;

