-- 两批合计：本文件 200 条应为 tier0=80 / tier1=70 / tier2=50（下面的分组还含 id 1~12 那 12 条老种子）
SELECT tier, COUNT(*) AS 条数, SUM(weight) AS 权重合计, MIN(effect_value) AS 最小每级值, MAX(effect_value) AS 最大每级值
FROM eq_skill_base WHERE scope = 0 GROUP BY tier ORDER BY tier;
-- 本文件 200 条是否全部落库（应为 200；小于 200 说明有 id 已被占用或被 IGNORE 跳过）
SELECT COUNT(*) AS 本次写入条数 FROM eq_skill_base WHERE scope = 0 AND skill_id BETWEEN 17 AND 216;
-- 名字重复检查（应无结果；后端按 name 展示，重名玩家会分不清是哪条）
SELECT name, COUNT(*) AS c, GROUP_CONCAT(skill_id) FROM eq_skill_base GROUP BY name HAVING c > 1;
-- 概率类（描述含“几率”）满级不得超过 30%，防失衡
SELECT skill_id, name, tier, effect_value, ROUND(effect_value * 50, 1) AS 满级值, description
FROM eq_skill_base WHERE skill_id BETWEEN 17 AND 216 AND description LIKE '%几率%' AND effect_value > 0.60;
-- 名字是否与老技能或两批之间撞车（应无结果；同上 GROUP BY name 一条已覆盖，留此句便于单独执行）
SELECT a.skill_id, a.name, b.skill_id FROM eq_skill_base a JOIN eq_skill_base b
  ON a.name = b.name AND a.skill_id < b.skill_id;
-- effect_type 归类缺口（应无结果；有行说明该技能没打标签，实装时会漏在按类 handler 之外）
SELECT skill_id, name, tier, scope, effect_type FROM eq_skill_base WHERE effect_type IS NULL ORDER BY skill_id;
