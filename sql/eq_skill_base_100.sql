--
-- 一、数值口径（必须先看懂再改数值）
--   技能等级 level = min(50, max(1, floor(Σ宝石等级 / 宝石槽数)))   —— 即“宝石平均等级”
--   效果数值 = effect_value × level；本文件所有 effect_value 都按【满级 Lv50 的目标值 ÷ 50】填写。
--   换算口诀：想让技能满级显示 X%，则 effect_value = X / 50。
--     例：0.20 → 满级 10%；0.40 → 满级 20%；1.00 → 满级 50%；0.10 → 满级 5%。
--   概率类技能的 effect_value 一律 ≤ 0.60（满级 30%），避免出现必定触发的失衡技能。
--
-- 二、文案硬约束（后端实现决定，写描述时必须遵守）
--   1) 每条技能【只能有一个随等级变化的数字】：fillEqSkillDesc 把所有 {v} 替换成同一个值，
--      所以“每层{v}%、最多{v}层”这种两个不同数值的需求做不到，层数/回合数/固定百分比要写成死数字。
--   2) description 里的 %、点、回合数直接给玩家看，勿用英文缩写。
--   3) 数值随等级实时变化，不落库，改本表后玩家重开炼化面板即生效，无需清缓存。
--
-- 三、档位与抽取（两批合计 200 条）
--   tier 0 初级书(454) 80 条（id 17~56 + 117~156）
--   tier 1 中级书(455) 70 条（id 57~91 + 157~191）
--   tier 2 高级书(456) 50 条（id 92~116 + 192~216）
--   另有原有 12 条（id 1~12）也属通用池，库中实测 tier = 3 条 0 档（id 1~3）/ 5 条 1 档（id 4~8）
--   / 4 条 2 档（id 9~12），所以三档容量为 83 / 75 / 54。
--   ⚠ id 13~16 是 scope=1 的英雄池示例，不在通用池抽取范围内。
--   weight 只在【同池内】比较相对概率，抽某条的概率 = 该条 weight ÷ 同池 weight 合计。
--   ⚠ 老 12 条的 weight（7~30）明显高于本文件新条目（5~28），而本文件条目多 16 倍，
--     结果是老技能反而更容易被抽中：抽一本中级书命中老 5 条之一的概率≈11%（110/974），
--     抽高级书命中老 4 条之一≈11%（35/314）。想让新旧手感一致就单独 UPDATE 那 12 条的 weight
--     （改 weight 只影响后续抽取，不影响玩家已保存的技能），本文件不擅自改。
--   设计梯度：低级=单一线性数值（无条件或极窄条件）；中级=带几率/阈值/双效果；
--            高级=叠层、回合递增、免死复活、守卫转移、全队联动等复合机制。
--
-- 四、effect_type 分类编号（本期仅作实装用的语义标签，代码暂未读取；实装时按类做 handler，
--     比逐个 match skill_id 省力得多）
