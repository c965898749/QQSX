--   15 条件增伤与减伤    16 守卫与伤害转移   17 次数与蓄力机制   18 免死与复活
--   19 队伍光环          20 成长型(叠层/递增/永久)            21 登场即范围伤害
--   22 行动限制类特殊规则(沉默敌方/增益不可驱散)
--
-- 五、幂等性
--   200 条新技能用 INSERT IGNORE：已存在的 skill_id 整行跳过，不会覆盖运营改过的名字/描述/权重。
